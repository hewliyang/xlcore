const FALLBACK_TILE = [0x11, 0x22, 0x44, 0x88, 0x11, 0x22, 0x44, 0x88];

const patternCache = new Map<string, CanvasPattern | null>();

function buildPattern(
  ctx: CanvasRenderingContext2D,
  preset: string,
  fg: string,
  bg: string | null,
): CanvasPattern | null {
  const key = `${preset}|${fg}|${bg ?? ""}`;
  const hit = patternCache.get(key);
  if (hit !== undefined) return hit;
  const tile = PATTERN_TILES[preset] ?? FALLBACK_TILE;
  const off = makeOffscreenCanvas(8, 8);
  const octx = off.getContext("2d")!;
  if (bg) {
    octx.fillStyle = bg;
    octx.fillRect(0, 0, 8, 8);
  }
  octx.fillStyle = fg;
  for (let y = 0; y < 8; y++) {
    const row = tile[y] ?? 0;
    for (let x = 0; x < 8; x++) {
      if (row & (1 << x)) octx.fillRect(x, y, 1, 1);
    }
  }
  const pat = ctx.createPattern(off as unknown as CanvasImageSource, "repeat");
  patternCache.set(key, pat);
  return pat;
}

export function pointFillStyle(
  ctx: CanvasRenderingContext2D,
  pf: ChartPointFill,
  rect: Rect,
): string | CanvasGradient | CanvasPattern | null {
  if (pf.kind === "gradient") {
    const stops = pf.gradientStops ?? [];
    if (stops.length === 0) return null;
    const a = ((pf.gradientAngle ?? 0) * Math.PI) / 180;
    const dx = Math.cos(a);
    const dy = Math.sin(a);
    const cx = rect.x + rect.w / 2;
    const cy = rect.y + rect.h / 2;
    const half = (Math.abs(dx) * rect.w + Math.abs(dy) * rect.h) / 2;
    const g = ctx.createLinearGradient(cx - dx * half, cy - dy * half, cx + dx * half, cy + dy * half);
    for (const s of stops) {
      const pos = Math.max(0, Math.min(1, (s.position ?? 0) / 100));
      g.addColorStop(pos, css(s.color, "#000000"));
    }
    return g;
  }
  if (pf.kind === "pattern") {
    const fg = css(pf.patternForeground, "#000000");
    const bg = pf.patternBackground ? css(pf.patternBackground, "#ffffff") : null;
    return buildPattern(ctx, pf.patternPreset ?? "", fg, bg);
  }
  return null;
}
