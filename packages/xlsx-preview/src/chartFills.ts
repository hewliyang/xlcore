export function pointFillAt(s: ChartSeries, index: number): ChartPointFill | undefined {
  return s.pointFills?.find((p) => p.index === index);
}

export function advancedPointFill(
  ctx: CanvasRenderingContext2D,
  s: ChartSeries,
  index: number,
  rect: Rect,
): string | CanvasGradient | CanvasPattern | null {
  const pf = pointFillAt(s, index);
  if (!pf) return null;
  return pointFillStyle(ctx, pf, rect);
}

function css(hex: string | undefined, fallback: string): string {
  if (!hex || hex.length === 0) return fallback;
  if (hex.startsWith("#")) return hex;
  if (/^[0-9a-fA-F]{8}$/.test(hex)) {
    const a = Number.parseInt(hex.slice(0, 2), 16) / 255;
    return `rgba(${Number.parseInt(hex.slice(2, 4), 16)},${Number.parseInt(hex.slice(4, 6), 16)},${Number.parseInt(hex.slice(6, 8), 16)},${a})`;
  }
  return `#${hex}`;
}

