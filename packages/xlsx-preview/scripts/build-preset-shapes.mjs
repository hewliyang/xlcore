#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "presetShapeDefinitions.xml");
const OUT = join(HERE, "..", "src", "presetShapeData.generated.ts");

function parseXml(src) {
  if (src.charCodeAt(0) === 0xfeff) src = src.slice(1);
  src = src.replace(/<\?xml[^?]*\?>/, "");
  const root = { name: "#root", attrs: {}, children: [] };
  const stack = [root];
  const tagRe = /<(\/?)([A-Za-z_][\w:-]*)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>/g;
  let m;
  while ((m = tagRe.exec(src)) !== null) {
    const [, close, name, attrsRaw, selfClose] = m;
    if (close) {
      const top = stack.pop();
      if (top.name !== name) {
        throw new Error(`mismatched close: </${name}> after <${top.name}>`);
      }
    } else {
      const attrs = {};
      const aRe = /([\w:-]+)="([^"]*)"/g;
      let am;
      while ((am = aRe.exec(attrsRaw)) !== null) attrs[am[1]] = am[2];
      const node = { name, attrs, children: [] };
      stack[stack.length - 1].children.push(node);
      if (!selfClose) stack.push(node);
    }
  }
  if (stack.length !== 1) {
    throw new Error(`unclosed elements: ${stack.map((s) => s.name).join(",")}`);
  }
  return root;
}

const FORMULA_OPS = new Set([
  "*/",
  "+-",
  "+/",
  "?:",
  "abs",
  "at2",
  "cat2",
  "cos",
  "max",
  "min",
  "mod",
  "pin",
  "sat2",
  "sin",
  "sqrt",
  "tan",
  "val",
]);

function parseFormula(fmla) {
  const toks = fmla.trim().split(/\s+/);
  const op = toks[0];
  if (!FORMULA_OPS.has(op)) {
    throw new Error(`unknown formula op: ${fmla}`);
  }
  return { op, args: toks.slice(1) };
}

function localName(name) {
  const i = name.indexOf(":");
  return i < 0 ? name : name.slice(i + 1);
}

function findChild(node, name) {
  for (const c of node.children) if (localName(c.name) === name) return c;
  return undefined;
}

function findChildren(node, name) {
  return node.children.filter((c) => localName(c.name) === name);
}

function gdEntries(parent, listName) {
  const list = findChild(parent, listName);
  if (!list) return [];
  return findChildren(list, "gd").map((gd) => ({
    name: gd.attrs.name,
    fmla: parseFormula(gd.attrs.fmla),
  }));
}

function pointAttrs(pt) {
  return { x: pt.attrs.x, y: pt.attrs.y };
}

function extractPath(path) {
  const cmds = [];
  for (const c of path.children) {
    const n = localName(c.name);
    switch (n) {
      case "moveTo": {
        const pt = findChild(c, "pt");
        cmds.push({ op: "M", ...pointAttrs(pt) });
        break;
      }
      case "lnTo": {
        const pt = findChild(c, "pt");
        cmds.push({ op: "L", ...pointAttrs(pt) });
        break;
      }
      case "arcTo": {
        cmds.push({
          op: "A",
          wR: c.attrs.wR,
          hR: c.attrs.hR,
          stAng: c.attrs.stAng,
          swAng: c.attrs.swAng,
        });
        break;
      }
      case "quadBezTo": {
        const pts = findChildren(c, "pt");
        cmds.push({ op: "Q", x1: pts[0].attrs.x, y1: pts[0].attrs.y, x: pts[1].attrs.x, y: pts[1].attrs.y });
        break;
      }
      case "cubicBezTo": {
        const pts = findChildren(c, "pt");
        cmds.push({
          op: "C",
          x1: pts[0].attrs.x, y1: pts[0].attrs.y,
          x2: pts[1].attrs.x, y2: pts[1].attrs.y,
          x: pts[2].attrs.x, y: pts[2].attrs.y,
        });
        break;
      }
      case "close":
        cmds.push({ op: "Z" });
        break;
      default:
        break;
    }
  }
  const out = { cmds };
  if (path.attrs.w) out.w = Number(path.attrs.w);
  if (path.attrs.h) out.h = Number(path.attrs.h);
  if (path.attrs.fill) out.fill = path.attrs.fill;
  if (path.attrs.stroke === "false") out.stroke = false;
  if (path.attrs.extrusionOk === "false") out.extrusionOk = false;
  return out;
}

function extractPreset(node) {
  const av = gdEntries(node, "avLst");
  const gd = gdEntries(node, "gdLst");
  const rectEl = findChild(node, "rect");
  const rect = rectEl
    ? { l: rectEl.attrs.l, t: rectEl.attrs.t, r: rectEl.attrs.r, b: rectEl.attrs.b }
    : undefined;
  const pathLst = findChild(node, "pathLst");
  const paths = pathLst ? findChildren(pathLst, "path").map(extractPath) : [];
  return { av, gd, rect, paths };
}

const xml = readFileSync(SRC, "utf8");
const tree = parseXml(xml);
const rootEl = tree.children.find((c) => c.name === "presetShapeDefinitons");
if (!rootEl) throw new Error("root <presetShapeDefinitons> not found");

const presets = {};
for (const node of rootEl.children) {
  presets[node.name] = extractPreset(node);
}

const json = JSON.stringify(presets);
const header = `// GENERATED by scripts/build-preset-shapes.mjs from
// ECMA-376 Part 1 Appendix D presetShapeDefinitions.xml.
// Do not edit by hand; re-run the script to regenerate.
`;

const body = `import type { PresetShapeTable } from "./presetShapeData.types.js";\n\nexport const PRESET_SHAPES: PresetShapeTable = ${json} as unknown as PresetShapeTable;\n`;

writeFileSync(OUT, header + "\n" + body);
console.log(`wrote ${OUT} (${Object.keys(presets).length} presets)`);
